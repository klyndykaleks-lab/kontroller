extern void xPortSysTickHandler(void);
extern volatile uint16_t Timer1, Timer2;

void SysTick_Handler(void)
{
  /* TIM11 is the HAL timebase. SysTick advances FreeRTOS only; incrementing
   * uwTick here as well makes every HAL_GetTick deadline run twice as fast. */
  if (xTaskGetSchedulerState() != taskSCHEDULER_NOT_STARTED)
  {
      xPortSysTickHandler();
  }

  if(Timer1 > 0) Timer1--;
  if(Timer2 > 0) Timer2--;
}

